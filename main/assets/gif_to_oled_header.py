#!/usr/bin/env python3
import argparse
from pathlib import Path

from PIL import Image, ImageSequence


def render_frame(frame, width, height, threshold, alpha_threshold, invert):
    frame = frame.convert("RGBA")
    frame.thumbnail((width, height), Image.Resampling.LANCZOS)

    canvas = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    x = (width - frame.width) // 2
    y = height - frame.height
    canvas.alpha_composite(frame, (x, y))

    out = [0] * (width * (height // 8))
    pixels = canvas.load()
    for py in range(height):
        page = py // 8
        bit = 1 << (py % 8)
        for px in range(width):
            r, g, b, a = pixels[px, py]
            lum = (r * 299 + g * 587 + b * 114) // 1000
            on = a >= alpha_threshold and lum >= threshold
            if invert:
                on = not on
            if on:
                out[page * width + px] |= bit
    return out


def write_header(frames, output, width, height, source_name):
    frame_size = width * (height // 8)
    lines = [
        f"// Auto-generated from {source_name}",
        f"// OLED Resolution: {width}x{height}",
        f"// Total frames: {len(frames)}",
        "// Generated by main/assets/gif_to_oled_header.py",
        "",
        "#ifndef GIF_FRAMES_H",
        "#define GIF_FRAMES_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define FRAME_COUNT {len(frames)}",
        f"#define FRAME_WIDTH {width}",
        f"#define FRAME_HEIGHT {height}",
        f"#define FRAME_SIZE {frame_size}",
        "#define GIF_COUNT 1",
        "",
        "typedef struct {",
        "    int startFrame;",
        "    int frameCount;",
        "} GifInfo;",
        "",
        "static const GifInfo gifInfo[GIF_COUNT] = {",
        f"    {{0, {len(frames)}}},",
        "};",
        "",
    ]

    for i, data in enumerate(frames):
        lines.append(f"static const uint8_t frame_{i}[FRAME_SIZE] = {{")
        for off in range(0, len(data), 16):
            chunk = ", ".join(f"0x{b:02X}" for b in data[off:off + 16])
            comma = "," if off + 16 < len(data) else ""
            lines.append(f"    {chunk}{comma}")
        lines.append("};")
        lines.append("")

    lines.append("static const uint8_t * const frames[FRAME_COUNT] = {")
    for i in range(len(frames)):
        comma = "," if i + 1 < len(frames) else ""
        lines.append(f"    frame_{i}{comma}")
    lines.extend([
        "};",
        "",
        "#endif // GIF_FRAMES_H",
        "",
    ])

    output.write_text("\n".join(lines), encoding="utf-8")


def main():
    script_dir = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description="Convert a GIF to a 1-bit SSD1306 OLED C header.")
    parser.add_argument("input", type=Path, nargs="?", default=script_dir / "1.gif", help="Input GIF path")
    parser.add_argument("-o", "--output", type=Path, default=script_dir.parent / "gif_frames.h", help="Output header path")
    parser.add_argument("--width", type=int, default=128, help="OLED width in pixels")
    parser.add_argument("--height", type=int, default=64, help="OLED height in pixels")
    parser.add_argument("--threshold", type=int, default=96, help="Luminance threshold, 0-255")
    parser.add_argument("--alpha-threshold", type=int, default=32, help="Alpha threshold, 0-255")
    parser.add_argument("--invert", action="store_true", help="Invert output pixels")
    args = parser.parse_args()

    if args.height % 8 != 0:
        raise SystemExit("height must be divisible by 8")

    image = Image.open(args.input)
    frames = [
        render_frame(frame, args.width, args.height, args.threshold, args.alpha_threshold, args.invert)
        for frame in ImageSequence.Iterator(image)
    ]
    if not frames:
        raise SystemExit("input GIF has no frames")

    output = args.output
    if not output.is_absolute():
        output = Path.cwd() / output
    output.parent.mkdir(parents=True, exist_ok=True)
    write_header(frames, output, args.width, args.height, args.input.name)
    print(f"wrote {len(frames)} frames to {output}")


if __name__ == "__main__":
    main()
